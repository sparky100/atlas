/**
 * E8 ("performance") phase 2's closing gate: "Targets asserted in a
 * Playwright timing spec: route change < 300 ms to content, action to
 * updated UI < 500 ms on the DNO model." Items (1)-(5) (#232, #233, #236,
 * #238, #240) are the work meant to hit these; this spec is the assertion
 * itself, not another measurement pass — `route-timing-measurement.engine.spec.ts`
 * (phase 1) already covers "generate the numbers, commit them, assert
 * nothing" and stays as the informational baseline. This spec reuses the
 * exact same DNO fixture, the same six routes, and the same three actions
 * (deliberately not shared as a helper — see this repo's precedent of
 * every perf/golden-path spec building its own fixture inline, e.g.
 * `architect-door-health-findings.engine.spec.ts`), but treats
 * `resolveToDataMs`/`wallClockMs` as hard assertions instead of a report.
 *
 * "Route change < 300 ms to content" is `resolve-to-data` — the full
 * `useRouteTiming.ts` window, not just first paint of a loading shell:
 * "content" is the route's own real data, and that's the number E8 items
 * (1)/(2)/(4) were built to shrink (shared cache, cached folds, deferred
 * non-critical panels). "Action to updated UI" is the same wall-clock
 * click→visible-result measurement phase 1 already used, now asserted
 * against 500ms — the number item (3)'s cache-seeding (no full reload
 * after a commit) was built to shrink.
 *
 * Same "needs a real Supabase" limitation as every other Playwright test
 * in this repo.
 */
import { existsSync, mkdirSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { randomUUID } from 'node:crypto';
import { expect, test, type Page } from '@playwright/test';
import { getMainBranch } from '../src/db/branches';
import { createChangeBranch } from '../src/db/branches';
import { createSupabaseClient } from '../src/db/client';
import { createComment } from '../src/db/comments';
import { commitToBranch } from '../src/db/commits';
import { createModel } from '../src/db/models';
import { createOrganisation } from '../src/db/organisations';
import { loadEnv } from '../src/db/env';
import { addUsesRelationship } from './fixtures/goldenPath';
import { buildEnvelope, generateDnoFixture, openChangeEditDelta, SYSTEM_COUNT } from './fixtures/dnoFixture';

const REPO_ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const ACCEPTANCE_DOC_PATH = path.join(REPO_ROOT, 'docs', 'perf', '2026-09-acceptance.md');

const ROUTE_TARGET_MS = 300;
const ACTION_TARGET_MS = 500;

interface RoutePerf {
  routeKey: string;
  label: string;
  resolveToDataMs: number | null;
}

interface ActionPerf {
  actionKey: string;
  label: string;
  wallClockMs: number;
}

/** Same shape as `route-timing-measurement.engine.spec.ts`'s own reader, trimmed to just the one number this spec asserts against — the network waterfall is that spec's own reporting concern, not this one's. */
async function readResolveToDataMs(page: Page, routeKey: string): Promise<number | null> {
  return page.evaluate((key) => performance.getEntriesByName(`atlas:${key}:resolve-to-data`, 'measure')[0]?.duration ?? null, routeKey);
}

function fmtMs(value: number | null): string {
  return value === null ? 'n/a' : `${value.toFixed(0)}ms`;
}

function renderReport(routes: RoutePerf[], actions: ActionPerf[]): string {
  const routeRows = routes.map((r) => `| ${r.label} | ${fmtMs(r.resolveToDataMs)} | ${r.resolveToDataMs !== null && r.resolveToDataMs < ROUTE_TARGET_MS ? '✅' : '❌'} |`).join('\n');
  const actionRows = actions.map((a) => `| ${a.label} | ${fmtMs(a.wallClockMs)} | ${a.wallClockMs < ACTION_TARGET_MS ? '✅' : '❌'} |`).join('\n');

  return `# Performance acceptance — 2026-09 (E8 phase 2)

Generated by \`e2e/route-timing-acceptance.engine.spec.ts\` against the DNO
model (\`e2e/fixtures/dnoFixture.ts\`: ${String(SYSTEM_COUNT)} systems), run
after E8 items (1)-(5) (#232, #233, #236, #238, #240) — compare against
\`docs/perf/2026-09.md\`'s own baseline, measured on the same fixture before
that work landed.

Targets (E8's own wording): route change < ${String(ROUTE_TARGET_MS)}ms to
content, action to updated UI < ${String(ACTION_TARGET_MS)}ms. Both are
asserted by this spec, not just reported — a run that fails either target
fails the test, not just this table.

## Routes: resolve → data complete

| Route | resolve→data | < ${String(ROUTE_TARGET_MS)}ms |
|---|---|---|
${routeRows}

## Actions: click → updated UI (wall clock)

| Action | time | < ${String(ACTION_TARGET_MS)}ms |
|---|---|---|
${actionRows}
`;
}

test('E8 acceptance: route change under 300ms, action-to-updated-UI under 500ms on the DNO model', async ({ page }) => {
  test.setTimeout(180_000);

  const env = loadEnv();
  const email = `perf-e8-accept-${randomUUID()}@example.test`;
  const password = `${randomUUID()}Aa1!`;

  await page.goto('/sign-in');
  await page.getByText("Don't have an account? Create one").click();
  await page.getByLabel('Email').fill(email);
  await page.getByLabel('Password').fill(password);
  await page.getByRole('button', { name: 'Create account' }).click();
  await expect(page.getByRole('heading', { name: 'Your organisations' })).toBeVisible();

  const signedIn = createSupabaseClient(env);
  const { error: signInError } = await signedIn.auth.signInWithPassword({ email, password });
  if (signInError) throw new Error(`perf-e8-accept fixture sign-in: ${signInError.message}`);
  const { data: userData, error: getUserError } = await signedIn.auth.getUser();
  if (getUserError) throw new Error(`perf-e8-accept fixture: could not read the signed-in user: ${getUserError.message}`);
  const userId = userData.user.id;

  const orgId = randomUUID();
  const orgSlug = `perf-e8-accept-${orgId.slice(0, 8)}`;
  await createOrganisation(signedIn, { id: orgId, name: 'DNO (E8 perf acceptance)', slug: orgSlug, createdBy: userId });

  const modelId = randomUUID();
  const modelSlug = `perf-e8-accept-model-${modelId.slice(0, 8)}`;
  await createModel(signedIn, { id: modelId, orgId, name: 'DNO', slug: modelSlug, createdBy: userId });

  const main = await getMainBranch(signedIn, modelId);
  if (!main) throw new Error('main branch was not auto-created');
  const genesisCommitId = main.head_commit_id;
  if (!genesisCommitId) throw new Error('main branch has no head commit (ADR-018 violation)');

  const { error: sourceError } = await signedIn.from('sources').insert({ id: randomUUID(), org_id: orgId, model_id: modelId, kind: 'manual', name: 'Seed', user_id: userId, created_by: userId });
  if (sourceError) throw new Error(`seed source: ${sourceError.message}`);
  const { data: sourceRow } = await signedIn.from('sources').select('id').eq('model_id', modelId).eq('user_id', userId).single();
  const seedSourceId = (sourceRow as { id: string }).id;

  const fixture = generateDnoFixture(seedSourceId);
  const seedEnvelope = buildEnvelope(main.id, genesisCommitId, `seed the DNO model (${String(SYSTEM_COUNT)} systems)`, fixture.deltas);
  const seedResult = await commitToBranch(signedIn, { modelId, branchId: main.id, expectedHeadCommitId: genesisCommitId, envelope: seedEnvelope });
  if (!seedResult.ok) throw new Error(`seeding the DNO fixture: ${seedResult.message}`);

  const { data: mainAfterSeed } = await signedIn.from('branches').select('head_commit_id').eq('id', main.id).single();
  const headAfterSeed = (mainAfterSeed as { head_commit_id: string }).head_commit_id;

  // "One open change" — see dnoFixture.ts's own module comment for why this
  // is a real edit on an open branch, not a genuine merge conflict.
  const changeBranch = await createChangeBranch(signedIn, { id: randomUUID(), orgId, modelId, name: 'vendor-refresh', title: 'Refresh System 01 vendor', createdBy: userId, mainHeadCommitId: headAfterSeed, intent: 'correct' });
  const changeEnvelope = buildEnvelope(changeBranch.id, headAfterSeed, 'update System 01 vendor', [openChangeEditDelta(seedSourceId, fixture.systemIds[0] ?? '', fixture.firstSystemCreateDeltaId)]);
  const changeResult = await commitToBranch(signedIn, { modelId, branchId: changeBranch.id, expectedHeadCommitId: headAfterSeed, envelope: changeEnvelope });
  if (!changeResult.ok) throw new Error(`seeding the open change: ${changeResult.message}`);

  // Two comments, on two different systems.
  await createComment(signedIn, { id: randomUUID(), orgId, modelId, anchorType: 'element', anchorId: fixture.systemIds[1] ?? '', body: 'Is this vendor contract still current?', authorId: userId });
  await createComment(signedIn, { id: randomUUID(), orgId, modelId, anchorType: 'element', anchorId: fixture.systemIds[2] ?? '', body: 'Confirmed with procurement — renewed through next year.', authorId: userId });

  const routes: RoutePerf[] = [];
  const actions: ActionPerf[] = [];

  // Same "wait on the mark itself, not a UI locator" reasoning as phase 1's
  // own `measure` helper — see that spec's doc comment on why a locator
  // check is the wrong signal here.
  async function measure(routeKey: string, label: string, urlPath: string): Promise<void> {
    await page.goto(urlPath);
    await page.waitForFunction((key) => performance.getEntriesByName(`atlas:${key}:data-complete`, 'mark').length > 0, routeKey, { timeout: 30_000 });
    routes.push({ routeKey, label, resolveToDataMs: await readResolveToDataMs(page, routeKey) });
  }

  // --- Six routes ---
  await measure('model-home', 'Model home', `/o/${orgSlug}/m/${modelSlug}`);
  await measure('capability-map', 'Capability map', `/o/${orgSlug}/m/${modelSlug}/capability-map`);
  await measure('landscape', 'Landscape', `/o/${orgSlug}/m/${modelSlug}/landscape`);
  await measure('elements', 'Elements (browse)', `/o/${orgSlug}/m/${modelSlug}/elements`);
  const firstSystemId = fixture.systemIds[3] ?? '';
  await measure('element-detail', 'Element detail', `/o/${orgSlug}/m/${modelSlug}/e/${firstSystemId}`);
  await measure('changes', 'Changes', `/o/${orgSlug}/m/${modelSlug}/changes`);

  // --- Three actions: add system, add relationship, save attribute ---
  const relSourceId = fixture.systemIds[4] ?? '';
  const relTargetName = `System ${String(6).padStart(2, '0')}`; // fixture's own naming, index 5 (0-based) -> "…System 06".
  await page.goto(`/o/${orgSlug}/m/${modelSlug}/e/${relSourceId}?ref=main`);
  await expect(page.getByRole('button', { name: 'Element actions' })).toBeVisible();
  {
    const t0 = Date.now();
    await addUsesRelationship(page, relTargetName, 'reads status from');
    await expect(page.getByRole('link', { name: new RegExp(relTargetName) }).first()).toBeVisible();
    actions.push({ actionKey: 'add-relationship', label: 'Add relationship (uses)', wallClockMs: Date.now() - t0 });
  }

  // Save attribute — a reload first, same reasoning as phase 1's own spec:
  // the previous action just moved this element's own head, and editing
  // against a stale in-memory copy would hit the real optimistic-concurrency
  // guard, not this spec's own timing logic. E8 item (3) means the page
  // *wouldn't* need this reload in practice (its own cache is seeded by the
  // commit that just landed) — kept here anyway so this measurement isolates
  // the save action itself, not whatever item (3) already fixed for the
  // action immediately before it.
  await page.reload();
  await expect(page.getByRole('button', { name: 'Element actions' })).toBeVisible();
  {
    const t0 = Date.now();
    await page.getByRole('button', { name: '✎ Edit' }).click();
    await page.getByLabel('Vendor', { exact: true }).fill('Measured Vendor Co');
    await page.getByRole('button', { name: 'Save' }).click();
    await expect(page.getByRole('button', { name: '✎ Edit' })).toBeVisible();
    actions.push({ actionKey: 'save-attribute', label: 'Save attribute (vendor)', wallClockMs: Date.now() - t0 });
  }

  // Add system — Home's own search-and-create flow.
  await page.goto(`/o/${orgSlug}/m/${modelSlug}`);
  await expect(page.getByRole('heading', { name: 'DNO' })).toBeVisible();
  {
    const newSystemName = `Perf Accept System ${randomUUID().slice(0, 8)}`;
    const t0 = Date.now();
    const searchBox = page.getByPlaceholder('Search or create a capability, system, or actor…');
    await expect(searchBox).toBeVisible();
    await searchBox.fill(newSystemName);
    await page.getByRole('button', { name: `Create system "${newSystemName}"` }).click();
    await expect(page.getByText('Description (required)')).toBeVisible();
    await page.getByPlaceholder('One line — what this system is').fill('Added during the E8 acceptance measurement pass.');
    await page.getByRole('button', { name: 'Skip capability' }).click();
    await expect(page.getByRole('heading', { name: newSystemName })).toBeVisible({ timeout: 15_000 });
    actions.push({ actionKey: 'add-system', label: 'Add system', wallClockMs: Date.now() - t0 });
  }

  const report = renderReport(routes, actions);
  console.log(report);
  const docsDir = path.dirname(ACCEPTANCE_DOC_PATH);
  if (!existsSync(docsDir)) mkdirSync(docsDir, { recursive: true });
  writeFileSync(ACCEPTANCE_DOC_PATH, report, 'utf8');

  // The actual gate: every route under 300ms, every action under 500ms.
  for (const route of routes) {
    expect(route.resolveToDataMs, `${route.label}: no resolve-to-data measurement was recorded at all`).not.toBeNull();
    expect(route.resolveToDataMs, `${route.label}: resolve-to-data was ${fmtMs(route.resolveToDataMs)}, target is <${String(ROUTE_TARGET_MS)}ms`).toBeLessThan(ROUTE_TARGET_MS);
  }
  for (const action of actions) {
    expect(action.wallClockMs, `${action.label}: took ${fmtMs(action.wallClockMs)}, target is <${String(ACTION_TARGET_MS)}ms`).toBeLessThan(ACTION_TARGET_MS);
  }
});
