import { build } from 'esbuild';
import { existsSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const dir = fileURLToPath(new URL('../supabase/functions/review-agent', import.meta.url));
const entry = `${dir}/_source/index.ts`;
if (!existsSync(entry)) throw new Error(`Review agent source missing: ${entry}`);

await build({
  entryPoints: [entry], outfile: `${dir}/index.ts`, bundle: true, format: 'esm', platform: 'neutral', target: 'es2022',
  external: ['https://esm.sh/@supabase/supabase-js@2.115.0', 'zod'],
  banner: { js: '// GENERATED by scripts/bundleReviewAgentFunction.ts; edit _source/index.ts instead.' },
});
