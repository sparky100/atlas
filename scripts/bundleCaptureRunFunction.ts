/**
 * Bundles `supabase/functions/capture-run/_source/index.ts` (the
 * hand-authored source, kept readable and editable) into a single flat
 * `supabase/functions/capture-run/index.ts` (generated, gitignored) that
 * `supabase functions deploy capture-run` actually ships.
 *
 * Why this exists: `_source/index.ts` and `_source/db.ts` reach into
 * `src/capture`, `src/engine`, and `src/contracts` using this repo's usual
 * bundler-style extension-less relative imports (`from './delta'`, Vite's
 * convention, not Deno's). Deno's edge runtime does not honour the
 * `sloppy-imports` unstable flag during `supabase functions deploy`'s own
 * graph-resolution step — confirmed against a real deploy attempt
 * ("failed to create the graph … Module not found"), not merely a
 * disclosed risk (see `docs/EDGE-FUNCTIONS.md`'s section on this
 * function). Pre-bundling the whole `src/` dependency chain into one file
 * with esbuild means Deno never has to resolve an extension-less relative
 * specifier at deploy time — only the small set of npm packages and the
 * one `esm.sh` URL import that were already left external, which
 * `supabase/functions/capture-run/deno.json`'s own `imports` map (or a
 * direct URL, for `@supabase/supabase-js`) already resolves.
 *
 * Run before every deploy: `pnpm functions:bundle:capture-run`, or via the
 * composite `pnpm functions:deploy:capture-run`.
 */
import { build } from 'esbuild';
import { existsSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const FUNCTION_DIR = fileURLToPath(new URL('../supabase/functions/capture-run', import.meta.url));
const ENTRY = `${FUNCTION_DIR}/_source/index.ts`;
const OUTFILE = `${FUNCTION_DIR}/index.ts`;

// Every bare specifier the transitive `src/` import graph reaches for at
// runtime (test-only imports like vitest/fast-check never run here and are
// excluded). Each of these must have a matching entry in `deno.json`'s
// `imports` map, or — for the one absolute-URL import — be resolvable by
// Deno directly. If a future `src/capture/*` change adds a new npm
// dependency to the graph, esbuild's own "Could not resolve" error below
// will name it; add it here and to `deno.json` together.
const EXTERNAL = ['https://esm.sh/@supabase/supabase-js@2.115.0', 'node:crypto', 'zod', 'xlsx', 'pdfjs-dist', 'pdfjs-dist/legacy/build/pdf.mjs', '@noble/hashes/sha2.js', '@noble/hashes/utils.js', '@anthropic-ai/sdk'];

async function main(): Promise<void> {
  if (!existsSync(ENTRY)) throw new Error(`bundleCaptureRunFunction: entry not found at ${ENTRY}`);

  const result = await build({
    entryPoints: [ENTRY],
    outfile: OUTFILE,
    bundle: true,
    format: 'esm',
    platform: 'neutral',
    target: 'es2022',
    external: EXTERNAL,
    logLevel: 'silent',
    banner: {
      js: [
        '// GENERATED by scripts/bundleCaptureRunFunction.ts (`pnpm functions:bundle:capture-run`) — do not edit directly.',
        '// Source lives at supabase/functions/capture-run/_source/index.ts and db.ts; edit those and re-run the bundle.',
      ].join('\n'),
    },
  });

  for (const warning of result.warnings) console.warn(warning.text);
  console.log(`Bundled ${ENTRY} -> ${OUTFILE}`);
}

main().catch((e: unknown) => {
  console.error(e);
  process.exitCode = 1;
});
