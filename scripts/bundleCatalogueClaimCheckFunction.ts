/**
 * Bundles `supabase/functions/catalogue-claim-check/_source/index.ts` (hand-authored)
 * and everything it reaches in `src/` into the flat, generated, git-ignored
 * `supabase/functions/catalogue-claim-check/index.ts` that `supabase functions deploy
 * catalogue-claim-check` ships. Same reason and shape as `bundleDesignAgentFunction.ts`:
 * Deno's deploy step cannot resolve this repo's extension-less relative
 * imports, so esbuild resolves them first and only the npm/URL specifiers in
 * `EXTERNAL` are left for Deno.
 *
 * Run before every deploy: `pnpm functions:bundle:catalogue-claim-check`, or the
 * composite `pnpm functions:deploy:catalogue-claim-check`.
 */
import { build } from 'esbuild';
import { existsSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const FUNCTION_DIR = fileURLToPath(new URL('../supabase/functions/catalogue-claim-check', import.meta.url));
const ENTRY = `${FUNCTION_DIR}/_source/index.ts`;
const OUTFILE = `${FUNCTION_DIR}/index.ts`;

// A new bare import reached from `src/tools` makes esbuild fail with "Could not resolve": add it here too.
const EXTERNAL = ['https://esm.sh/@supabase/supabase-js@2.115.0', 'zod'];

async function main(): Promise<void> {
  if (!existsSync(ENTRY)) throw new Error(`bundleCatalogueClaimCheckFunction: entry not found at ${ENTRY}`);

  const result = await build({
    entryPoints: [ENTRY],
    outfile: OUTFILE,
    bundle: true,
    format: 'esm',
    platform: 'neutral',
    target: 'es2022',
    external: EXTERNAL,
    logLevel: 'silent',
    banner: {
      js: [
        '// GENERATED by scripts/bundleCatalogueClaimCheckFunction.ts (`pnpm functions:bundle:catalogue-claim-check`) - do not edit directly.',
        '// Source lives at supabase/functions/catalogue-claim-check/_source/index.ts; edit that and re-run the bundle.',
      ].join('\n'),
    },
  });

  for (const warning of result.warnings) console.warn(warning.text);
  console.log(`Bundled ${ENTRY} -> ${OUTFILE}`);
}

main().catch((e: unknown) => {
  console.error(e);
  process.exitCode = 1;
});
