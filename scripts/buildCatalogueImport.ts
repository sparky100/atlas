/**
 * `pnpm content:build-catalogue-import` — catalogue maintenance step 3
 * (proposals/PROPOSAL-catalogue-maintenance.md). The one and only time the
 * `content/catalogue` files are a source: reads them, merges the same product
 * across sectors, and writes the one-off import migration
 * `supabase/migrations/20261126210000_catalogue_import_from_files.sql`.
 *
 * The merge is a pure function (`mergeCatalogueFiles`) so a reviewer can read
 * and test it. The migration resolves each link against the live capability
 * sets itself and loads nothing where those sets do not exist (a test
 * database), so tests are never seeded with product data.
 */
import { readdir, readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { productCatalogueContentSchema, type ProductCatalogueContent } from '../src/contracts/productCatalogue';
import { isCliEntrypoint } from './isCliEntrypoint';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const OUTPUT = path.join(ROOT, 'supabase', 'migrations', '20261126210000_catalogue_import_from_files.sql');

export interface ImportLink { sector: string; mapVersion: number; code: string; how: string }
export interface ImportClaim { kind: string; statement: string; sourceUrl: string; sourceDate: string }
export interface ImportProduct {
  code: string; product: string; vendor: string; summary: string;
  links: ImportLink[]; claims: ImportClaim[];
}

const identity = (vendor: string, product: string): string => `${vendor.trim().toLowerCase()}\u0000${product.trim().toLowerCase()}`;

/**
 * One product per vendor and product name. For each sector only the newest
 * file counts (a later version corrects an earlier one). Links are kept per
 * sector and set; claims are the union, with the same kind, statement and
 * source counted once at its newest source date. Reviewers named in the files
 * are not carried: every claim is loaded as drafted.
 */
export function mergeCatalogueFiles(files: readonly ProductCatalogueContent[]): ImportProduct[] {
  const newest = new Map<string, ProductCatalogueContent>();
  for (const file of files) {
    const current = newest.get(file.sector);
    if (!current || file.version > current.version) newest.set(file.sector, file);
  }
  const ordered = [...newest.values()].sort((a, b) => a.sector.localeCompare(b.sector));
  const merged = new Map<string, ImportProduct>();
  for (const file of ordered) {
    for (const entry of file.entries) {
      const key = identity(entry.vendor, entry.product);
      const product = merged.get(key) ?? { code: entry.code, product: entry.product, vendor: entry.vendor, summary: entry.summary, links: [], claims: [] };
      for (const link of entry.capabilities) {
        product.links.push({ sector: file.sector, mapVersion: file.capabilityMapVersion, code: link.code, how: link.howItSupports });
      }
      for (const claim of entry.claims) {
        const same = product.claims.find((existing) => existing.kind === claim.kind && existing.statement === claim.statement && existing.sourceUrl === claim.sourceUrl);
        if (same) {
          if (claim.sourceDate > same.sourceDate) same.sourceDate = claim.sourceDate;
        } else {
          product.claims.push({ kind: claim.kind, statement: claim.statement, sourceUrl: claim.sourceUrl, sourceDate: claim.sourceDate });
        }
      }
      merged.set(key, product);
    }
  }
  const codes = new Map<string, string>();
  for (const [key, product] of merged) {
    const owner = codes.get(product.code);
    if (owner !== undefined && owner !== key) throw new Error(`Code ${product.code} is used by two different products`);
    codes.set(product.code, key);
  }
  return [...merged.values()].sort((a, b) => a.vendor.localeCompare(b.vendor) || a.product.localeCompare(b.product));
}

async function readFiles(): Promise<ProductCatalogueContent[]> {
  const root = path.join(ROOT, 'content', 'catalogue');
  const out: ProductCatalogueContent[] = [];
  for (const sector of await readdir(root, { withFileTypes: true })) {
    if (!sector.isDirectory()) continue;
    for (const file of await readdir(path.join(root, sector.name))) {
      if (!file.endsWith('.json')) continue;
      const parsed = productCatalogueContentSchema.safeParse(JSON.parse(await readFile(path.join(root, sector.name, file), 'utf8')) as unknown);
      if (!parsed.success) throw new Error(`${sector.name}/${file}: ${parsed.error.message}`);
      out.push(parsed.data);
    }
  }
  return out;
}

const HEADER = `-- Catalogue maintenance step 3: load the product files into the library, once.
-- Generated by scripts/buildCatalogueImport.ts from content/catalogue (never
-- hand-edited). This is the last time those files are a source.
--
-- For each product, matched on vendor and product name (or code) against the
-- library: create it if it is missing, add the shared and sector capability
-- links that resolve against the current published capability sets, and add
-- any claim whose statement is not already there. Every claim arrives drafted,
-- origin "imported", with no reviewer, whatever the file said. A product none
-- of whose links resolve is skipped, so a database without the real capability
-- sets (every test database) loads nothing. Existing products, claims and
-- reviews are never changed or removed; published catalogues are untouched.
-- Re-running adds nothing a second time.
`;

const BODY = `
do $import_run$
declare
  v_data jsonb := $import$__DATA__$import$::jsonb;
  v_actor constant uuid := '00000000-0000-0000-0000-000000000000';
  v_by constant text := 'Loaded from files';
  p jsonb;
  l jsonb;
  c jsonb;
  v_id uuid;
  v_map uuid;
  v_item uuid;
  v_name text;
  v_revision int;
  v_resolved int;
  v_added int;
  v_next int;
  n_products int := 0; n_created int := 0; n_skipped int := 0;
  n_shared int := 0; n_sector int := 0; n_unresolved int := 0;
  n_claims int := 0; n_claims_seen int := 0;
begin
  for p in select value from jsonb_array_elements(v_data) loop
    n_products := n_products + 1;
    v_resolved := 0;
    for l in select value from jsonb_array_elements(p -> 'links') loop
      select i.id into v_item from public.capability_map_items i
        join public.capability_maps m on m.id = i.map_id
        where m.sector = l ->> 'sector' and m.version = (l ->> 'mapVersion')::int
          and m.status = 'published' and i.code = l ->> 'code';
      if v_item is not null then v_resolved := v_resolved + 1; end if;
      v_item := null;
    end loop;
    if v_resolved = 0 then n_skipped := n_skipped + 1; continue; end if;

    v_id := null;
    select id into v_id from public.catalogue_products
      where lower(btrim(vendor)) = lower(btrim(p ->> 'vendor'))
        and lower(btrim(product)) = lower(btrim(p ->> 'product'));
    if v_id is null then
      select id into v_id from public.catalogue_products where code = p ->> 'code';
    end if;
    v_added := 0;
    if v_id is null then
      insert into public.catalogue_products(code, product, vendor, summary, created_by, updated_by)
      values (p ->> 'code', p ->> 'product', p ->> 'vendor', p ->> 'summary', v_actor, v_actor)
      returning id, edit_revision into v_id, v_revision;
      insert into public.catalogue_product_events(product_id, action, actor_id, actor_name, edit_revision)
      values (v_id, 'created', v_actor, v_by, v_revision);
      n_created := n_created + 1;
    end if;

    for l in select value from jsonb_array_elements(p -> 'links') loop
      v_item := null; v_map := null;
      select i.id, m.id, i.name into v_item, v_map, v_name from public.capability_map_items i
        join public.capability_maps m on m.id = i.map_id
        where m.sector = l ->> 'sector' and m.version = (l ->> 'mapVersion')::int
          and m.status = 'published' and i.code = l ->> 'code';
      if v_item is null then n_unresolved := n_unresolved + 1; continue; end if;
      if exists (select 1 from public.reference_map_item_links r where r.map_item_id = v_item) then
        insert into public.catalogue_product_general_links(product_id, capability_id, how_it_supports)
          select v_id, r.capability_id, l ->> 'how'
          from public.reference_map_item_links r where r.map_item_id = v_item
          on conflict do nothing;
        if found then n_shared := n_shared + 1; v_added := v_added + 1; end if;
      else
        insert into public.catalogue_product_capabilities(product_id, capability_map_id, capability_code, capability_name, how_it_supports)
        values (v_id, v_map, l ->> 'code', v_name, l ->> 'how')
        on conflict do nothing;
        if found then n_sector := n_sector + 1; v_added := v_added + 1; end if;
      end if;
    end loop;

    for c in select value from jsonb_array_elements(p -> 'claims') loop
      n_claims_seen := n_claims_seen + 1;
      -- The same statement is the same claim, whatever its source link.
      if exists (select 1 from public.catalogue_product_claims x
                 where x.product_id = v_id and x.kind = c ->> 'kind' and x.statement = c ->> 'statement') then
        continue;
      end if;
      select coalesce(max(position), 0) + 1 into v_next from public.catalogue_product_claims where product_id = v_id;
      insert into public.catalogue_product_claims(product_id, position, kind, statement, source_url, source_date,
        review_state, origin, drafted_by, drafted_by_name, drafted_at, reviewed_by, reviewed_by_user, reviewed_at)
      values (v_id, v_next, c ->> 'kind', c ->> 'statement', c ->> 'sourceUrl', (c ->> 'sourceDate')::date,
        'drafted', 'imported', null, null, now(), null, null, null);
      n_claims := n_claims + 1; v_added := v_added + 1;
    end loop;

    if v_added > 0 and v_revision is null then
      update public.catalogue_products set edit_revision = edit_revision + 1, updated_at = now()
        where id = v_id returning edit_revision into v_revision;
      insert into public.catalogue_product_events(product_id, action, actor_id, actor_name, edit_revision)
      values (v_id, 'saved', v_actor, v_by, v_revision);
    end if;
    v_revision := null;
  end loop;
  raise notice 'catalogue import: % products in the files, % created, % skipped (no link resolved), % shared links, % sector links, % links not in their set, % of % claims added as drafted',
    n_products, n_created, n_skipped, n_shared, n_sector, n_unresolved, n_claims, n_claims_seen;
end
$import_run$;
`;

export function renderMigration(products: readonly ImportProduct[]): string {
  const data = JSON.stringify(products, null, 1);
  if (data.includes('$import$')) throw new Error('The data contains the SQL quote tag');
  return HEADER + BODY.replace('__DATA__', () => data);
}

async function main(): Promise<void> {
  const products = mergeCatalogueFiles(await readFiles());
  await writeFile(OUTPUT, renderMigration(products), 'utf8');
  const claims = products.reduce((total, product) => total + product.claims.length, 0);
  const links = products.reduce((total, product) => total + product.links.length, 0);
  console.log(`${String(products.length)} products, ${String(links)} links, ${String(claims)} claims -> ${path.relative(ROOT, OUTPUT)}`);
}

if (isCliEntrypoint(import.meta.url)) {
  main().catch((error: unknown) => { console.error(error); process.exitCode = 1; });
}
