/**
 * Bundles `supabase/functions/design-agent/_source/index.ts` (hand-authored) and
 * everything it reaches in `src/` into the flat, generated, git-ignored
 * `supabase/functions/design-agent/index.ts` that `supabase functions deploy
 * design-agent` ships. Same reason and shape as `bundleCaptureRunFunction.ts`:
 * Deno's deploy step cannot resolve this repo's extension-less relative
 * imports, so esbuild resolves them first and only the npm/URL specifiers in
 * `EXTERNAL` are left for `supabase/functions/design-agent/deno.json`.
 *
 * Run before every deploy: `pnpm functions:bundle:design-agent`, or the
 * composite `pnpm functions:deploy:design-agent`.
 */
import { build } from 'esbuild';
import { existsSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const FUNCTION_DIR = fileURLToPath(new URL('../supabase/functions/design-agent', import.meta.url));
const ENTRY = `${FUNCTION_DIR}/_source/index.ts`;
const OUTFILE = `${FUNCTION_DIR}/index.ts`;

// A new bare import reached from `src/tools` makes esbuild fail with "Could not resolve": add it here and to `deno.json` together.
const EXTERNAL = ['https://esm.sh/@supabase/supabase-js@2.115.0', 'zod'];

async function main(): Promise<void> {
  if (!existsSync(ENTRY)) throw new Error(`bundleDesignAgentFunction: entry not found at ${ENTRY}`);

  const result = await build({
    entryPoints: [ENTRY],
    outfile: OUTFILE,
    bundle: true,
    format: 'esm',
    platform: 'neutral',
    target: 'es2022',
    external: EXTERNAL,
    logLevel: 'silent',
    banner: {
      js: [
        '// GENERATED by scripts/bundleDesignAgentFunction.ts (`pnpm functions:bundle:design-agent`) — do not edit directly.',
        '// Source lives at supabase/functions/design-agent/_source/index.ts; edit that and re-run the bundle.',
      ].join('\n'),
    },
  });

  for (const warning of result.warnings) console.warn(warning.text);
  console.log(`Bundled ${ENTRY} -> ${OUTFILE}`);
}

main().catch((e: unknown) => {
  console.error(e);
  process.exitCode = 1;
});
